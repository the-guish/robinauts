"""The inbound side: HTTP in, application calls out, responses back.

It translates and **decides nothing** (``docs/layout.md``): a route reads a
request, calls one application method and turns what comes back into a status,
a body, a cookie or a ``Location``. Every rule it appears to apply -- who may
sign in, whether a return target is safe, what an ID token is worth -- is
applied below it, and every service it uses is handed to it by the composition
root. It depends on ``robinauts.legacy.application`` and ``robinauts.legacy.domain`` and on
nothing else inside the package.

FastAPI, Starlette and Pydantic live here and in the composition root, and
nowhere else (``docs/specs/backend.md``, "Web"); an import-linter contract in
``backend/pyproject.toml`` says so and the test suite runs it.

AG-UI lives here too, and only here (``docs/specs/wire.md``): the application
publishes the platform's own turn events and ``agui`` maps them to the events a
chat client reads.

What is here: the ``/auth`` routes and ``/health`` (``auth_routes``,
``web``), the conversation routes (``conversation_routes``), the streaming
ones that start a turn and follow one (``stream_routes``, ``agui``) and the
agents and models a conversation is started with (``agent_routes``), the built interface
under ``/ui/`` and the redirects that lead to it (``ui``), what each of them
can refuse with as the OpenAPI document says it (``refusals``), the cookies a sign-in
uses (``cookies``), who is asking and what each route needs of them
(``access``), the checks every write passes before anything reads it
(``protection``), how an error crosses HTTP (``errors``), and the shapes the
JSON API sends (``schemas``).
"""

